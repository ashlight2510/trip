import fs from "node:fs";
import path from "node:path";
import { insertOrder } from "../src/db/relations";
import { read } from "./lib/store";

const literal = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v)) return `array[${v.map(literal).join(", ")}]::text[]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const out = ["-- generated by `npm run data:sql` from data/*.json", "begin;", ""];

for (const name of insertOrder) {
  const rows = read(name) as Record<string, unknown>[];
  if (rows.length === 0) continue;
  const cols = Object.keys(rows[0]);
  out.push(`insert into ${name} (${cols.join(", ")}) values`);
  out.push(rows.map((r) => `  (${cols.map((c) => literal(r[c])).join(", ")})`).join(",\n") + ";", "");
}

out.push("commit;", "");
const target = path.join(process.cwd(), "db", "seed.sql");
fs.writeFileSync(target, out.join("\n"));
console.log(`작성 완료: ${path.relative(process.cwd(), target)}`);
