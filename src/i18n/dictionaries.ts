function koIro(name: string): "으로" | "로" {
  const ch = name.charCodeAt(name.length - 1);
  if (!name || ch < 0xac00 || ch > 0xd7a3) return "으로";
  return (ch - 0xac00) % 28 === 0 ? "로" : "으로";
}

